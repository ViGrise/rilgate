use std::{collections::BTreeMap, fs, path::Path};

use anyhow::{Context, Result, bail, ensure};
use sha2::{Digest, Sha256};
use swc_core::{
  base::{Compiler, config::Options},
  common::{FileName, GLOBALS, Globals, SourceMap, errors::Handler, sync::Lrc},
  ecma::{
    ast::*,
    parser::{Parser, StringInput, Syntax, lexer::Lexer},
    visit::{Visit, VisitWith},
  },
};

const COMPILER: &str = "swc_core 82.1.1; es5; inline helpers; strict IIFE; recipe 1";
const STARTUP: &[&str] = &[
  "challenge/promise.js",
  "challenge/runtime.js",
  "challenge/registry.js",
  "challenge/stratum-pool.js",
  "solvers/fast/worker.js",
  "solvers/fast/solver.js",
  "solvers/fast/adapter.js",
  "solvers/randomx/adapter.js",
  "solvers/hashwx/adapter.js",
  "challenge.js",
];
const WORKER: &str = "solvers/fast/worker.js";
const NOTICE: &str = include_str!("web-notice.txt");

pub fn build(root: &Path) -> Result<()> {
  let directory = root.join("crates/rilgate-web/generated");
  let compiler = Compiler::new(Lrc::<SourceMap>::default());
  validate_es5(&fs::read_to_string(root.join("web/static/js/page.js"))?)?;
  let mut outputs = BTreeMap::new();
  let mut entries = Vec::new();
  let mut bundle = String::new();
  for name in STARTUP {
    let source = format!("static/js/{name}");
    let bytes = fs::read(root.join("web").join(&source)).with_context(|| source.clone())?;
    let text = std::str::from_utf8(&bytes)?;
    let code = compile(&compiler, name, text)?;
    validate_es5(&code).with_context(|| format!("Validating ES5 output for {name}"))?;
    bundle.push_str(&code);
    entries.push(serde_json::json!({
      "source": source,
      "output": name,
      "sha256": hex::encode(Sha256::digest(&bytes)),
    }));
    outputs.insert(name.to_string(), code.into_bytes());
  }
  validate_es5(&bundle).context("Validating assembled ES5 startup bundle")?;
  outputs.insert(
    "manifest.json".into(),
    (serde_json::to_string_pretty(&serde_json::json!({
      "compiler": COMPILER,
      "startup": entries,
      "worker": WORKER,
    }))?
      + "\n")
      .into_bytes(),
  );
  outputs.insert("NOTICE".into(), NOTICE.as_bytes().to_vec());
  fs::create_dir_all(&directory)?;
  for name in output_files(&directory)? {
    if !outputs.contains_key(&name) {
      fs::remove_file(directory.join(name))?;
    }
  }
  for (name, bytes) in outputs {
    let path = directory.join(name);
    fs::create_dir_all(path.parent().context("Generated output parent")?)?;
    fs::write(&path, bytes).with_context(|| format!("Writing {}", path.display()))?;
  }
  println!("Wrote ES5 browser resources to {}", directory.display());
  Ok(())
}

fn output_files(directory: &Path) -> Result<Vec<String>> {
  fn collect(root: &Path, directory: &Path, out: &mut Vec<String>) -> Result<()> {
    if !directory.exists() {
      return Ok(());
    }
    for entry in fs::read_dir(directory)? {
      let path = entry?.path();
      if path.is_dir() {
        collect(root, &path, out)?;
      } else {
        out.push(
          path
            .strip_prefix(root)?
            .to_string_lossy()
            .replace('\\', "/"),
        );
      }
    }
    Ok(())
  }
  let mut files = Vec::new();
  collect(directory, directory, &mut files)?;
  files.sort();
  Ok(files)
}

fn compile(compiler: &Compiler, name: &str, source: &str) -> Result<String> {
  let options: Options = serde_json::from_value(serde_json::json!({
    "swcrc": false,
    "configFile": false,
    "isModule": false,
    "minify": false,
    "jsc": { "target": "es5", "externalHelpers": false, "parser": { "syntax": "ecmascript" } },
  }))?;
  let handler =
    Handler::with_emitter_writer(Box::new(std::io::stderr()), Some(compiler.cm.clone()));
  let file = compiler.cm.new_source_file(
    FileName::Custom(name.to_string()).into(),
    format!("\"use strict\";\n{source}\n"),
  );
  let output = GLOBALS.set(&Globals::new(), || {
    compiler.process_js_file(file, &handler, &options)
  })?;
  Ok(format!(
    "/*! Generated by {COMPILER}.\n{NOTICE}*/\n(function () {{\n\"use strict\";\n{}\n}})();\n",
    output.code
  ))
}

fn validate_es5(source: &str) -> Result<()> {
  let map = Lrc::<SourceMap>::default();
  let file = map.new_source_file(FileName::Anon.into(), source.to_owned());
  let mut parser = Parser::new_from(Lexer::new(
    Syntax::Es(Default::default()),
    EsVersion::Es5,
    StringInput::from(&*file),
    None,
  ));
  let script = parser
    .parse_script()
    .map_err(|error| anyhow::anyhow!("{error:?}"))?;
  ensure!(parser.take_errors().is_empty(), "Invalid generated script");
  // SWC's target controls transforms, so syntax validation also checks the parsed tree.
  let mut syntax = Es5Syntax { invalid: false };
  script.visit_with(&mut syntax);
  if syntax.invalid {
    bail!("Generated script contains syntax newer than ES5");
  }
  Ok(())
}

struct Es5Syntax {
  invalid: bool,
}
impl Visit for Es5Syntax {
  fn visit_expr(&mut self, node: &Expr) {
    if matches!(
      node,
      Expr::Arrow(_)
        | Expr::Class(_)
        | Expr::Await(_)
        | Expr::Yield(_)
        | Expr::Tpl(_)
        | Expr::TaggedTpl(_)
        | Expr::MetaProp(_)
        | Expr::OptChain(_)
    ) {
      self.invalid = true;
    }
    node.visit_children_with(self);
  }
  fn visit_call_expr(&mut self, node: &CallExpr) {
    if let Callee::Expr(callee) = &node.callee
      && let Expr::Ident(name) = &**callee
    {
      self.invalid |= matches!(&*name.sym, "require" | "eval" | "Function");
    }
    node.visit_children_with(self);
  }
  fn visit_new_expr(&mut self, node: &NewExpr) {
    if let Expr::Ident(name) = &*node.callee {
      self.invalid |= name.sym == *"Function";
    }
    node.visit_children_with(self);
  }
  fn visit_function(&mut self, node: &Function) {
    self.invalid |= node.is_async || node.is_generator;
    node.visit_children_with(self);
  }
  fn visit_decl(&mut self, node: &Decl) {
    self.invalid |= !matches!(node, Decl::Fn(_) | Decl::Var(_));
    node.visit_children_with(self);
  }
  fn visit_catch_clause(&mut self, node: &CatchClause) {
    self.invalid |= node.param.is_none();
    node.visit_children_with(self);
  }
  fn visit_class(&mut self, _: &Class) {
    self.invalid = true;
  }
  fn visit_pat(&mut self, node: &Pat) {
    self.invalid |= !matches!(node, Pat::Ident(_) | Pat::Expr(_));
    node.visit_children_with(self);
  }
  fn visit_var_decl(&mut self, node: &VarDecl) {
    self.invalid |= node.kind != VarDeclKind::Var;
    node.visit_children_with(self);
  }
  fn visit_prop(&mut self, node: &Prop) {
    self.invalid |= matches!(node, Prop::Shorthand(_) | Prop::Method(_) | Prop::Assign(_));
    node.visit_children_with(self);
  }
  fn visit_prop_name(&mut self, node: &PropName) {
    self.invalid |= matches!(node, PropName::Computed(_));
    node.visit_children_with(self);
  }
  fn visit_spread_element(&mut self, _: &SpreadElement) {
    self.invalid = true;
  }
  fn visit_for_of_stmt(&mut self, _: &ForOfStmt) {
    self.invalid = true;
  }
  fn visit_big_int(&mut self, _: &BigInt) {
    self.invalid = true;
  }
  fn visit_callee(&mut self, node: &Callee) {
    self.invalid |= matches!(node, Callee::Import(_) | Callee::Super(_));
    node.visit_children_with(self);
  }
  fn visit_bin_expr(&mut self, node: &BinExpr) {
    self.invalid |= matches!(node.op, BinaryOp::Exp | BinaryOp::NullishCoalescing);
    node.visit_children_with(self);
  }
  fn visit_assign_expr(&mut self, node: &AssignExpr) {
    self.invalid |= matches!(
      node.op,
      AssignOp::ExpAssign | AssignOp::AndAssign | AssignOp::OrAssign | AssignOp::NullishAssign
    );
    node.visit_children_with(self);
  }
  fn visit_number(&mut self, node: &Number) {
    if let Some(raw) = &node.raw {
      self.invalid |= raw.contains('_')
        || raw.starts_with("0b")
        || raw.starts_with("0B")
        || raw.starts_with("0o")
        || raw.starts_with("0O");
    }
  }
  fn visit_str(&mut self, node: &Str) {
    if let Some(raw) = &node.raw {
      self.invalid |= raw.contains("\\u{");
    }
  }
  fn visit_regex(&mut self, node: &Regex) {
    self.invalid |=
      node.flags.chars().any(|flag| !"gim".contains(flag)) || node.exp.contains("(?<");
  }
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn syntax_gate_rejects_modern_constructs() {
    for source in [
      "require('x')",
      "eval('x')",
      "new Function('x')",
      "Function('x')",
      "using x = y;",
      "try {} catch {}",
      "var x = /(?<name>x)/",
      "let x = 1",
      "const f = () => 1",
      "async function f() {}",
      "function* f() {}",
      "var x = `x`",
      "var x = a?.b",
      "var x = {...a}",
      "var x = {a}",
      "var x = 1n",
      "import('x')",
      "var x = 0b10",
      "var x = 1_000",
      "var x = /x/u",
      "var x = a ** b",
      "var x = a ?? b",
      "class X {}",
      "for (var x of y) {}",
      "var [x] = y",
      "function f(x = 1) {}",
    ] {
      assert!(validate_es5(source).is_err(), "{source}");
    }
    validate_es5("'use strict'; var x = function (a) { return a + 1; }; x(1);").unwrap();
  }
}
